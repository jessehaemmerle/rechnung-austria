export type DocTextKey = keyof (typeof docTexts)['de'];

export function t(lang: Language, key: DocTextKey, vars: Record<string, string | number> = {}): string {
  return Object.entries(vars).reduce<string>((s, [k, v]) => s.split(`{${k}}`).join(String(v)), docTexts[lang][key]);
}

export function kindLabel(kind: DocumentKind, lang: Language): string {
  return docTexts[lang][kind];
}
